"""1930 complaint draft (F5): Markdown + PDF built from what the call actually recorded.

It is a DRAFT the user reviews and files themselves at cybercrime.gov.in or by calling 1930. Nothing here submits
anything anywhere. Whether money or an OTP was shared is only what the user tells us (None = not answered yet).
"""

import json
import re
import time
from dataclasses import dataclass, field
from pathlib import Path
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.alerts import IST, STAGE_NAMES, ist_now
from datetime import datetime

BANNER = "DRAFT — review before filing. Generated by Kavach from a recorded call. Nothing has been submitted."
NEXT_STEPS = [
    "Call 1930 (National Cyber Crime Helpline) as soon as possible. Early reports give the best chance to freeze money.",
    "File the complaint at https://cybercrime.gov.in using the details below.",
    "Report the caller's number on Sanchar Saathi (Chakshu): https://sancharsaathi.gov.in",
    "Contact your bank now to freeze or dispute any payment, and block any card you shared.",
    "Do not delete anything. Keep this draft, the call log and any screenshots or messages.",
]
EVIDENCE_LABELS = [
    ("person_name", "Name(s) the caller gave"), ("agency", "Organisation / agency claimed"),
    ("officer_id", "Officer, badge or case IDs"), ("amount", "Amounts demanded"), ("upi_id", "UPI IDs"),
    ("bank_account", "Bank account numbers"), ("ifsc", "IFSC codes"), ("phone_number", "Phone numbers given"),
    ("url", "Links"), ("email", "E-mail addresses"), ("app_name", "Apps the caller asked to install or use"),
]


@dataclass
class Report:
    call_id: str
    incident_time: str
    duration: str
    caller_number: str
    stages: list[str]
    peak_risk: float
    warned_at: str | None
    takeover_at: str | None
    evidence: dict[str, list[str]]
    key_quotes: list[dict]
    transcript: list[dict]
    money_shared: bool | None
    otp_shared: bool | None
    notes: str = ""
    missing: list[str] = field(default_factory=list)


def _ist(ts: float | None) -> str | None:
    return datetime.fromtimestamp(ts, IST).strftime("%d %b %Y, %H:%M:%S IST") if ts else None


def _clock(ts: float) -> str:
    return datetime.fromtimestamp(ts, IST).strftime("%H:%M:%S")


def _yn(v: bool | None) -> str:
    return "Not answered yet — please confirm" if v is None else ("YES" if v else "No")


def build(store, call_id: str, notes: str = "") -> Report:
    call = store.query("SELECT * FROM calls WHERE id=?", (call_id,))
    if not call:
        raise KeyError(call_id)
    call = call[0]
    turns = store.turns(call_id)
    events = store.events(call_id)
    wall = {e["payload"].get("turn_id"): e["ts_wall"] for e in events if e["type"] == "turn_final"}
    detections = store.query("SELECT * FROM detections WHERE call_id=? ORDER BY id", (call_id,))
    stages = sorted({s for d in detections for s in json.loads(d["stages"] or "[]")})
    evidence: dict[str, list[str]] = {}
    for row in store.query("SELECT type, value FROM evidence WHERE call_id=? AND valid=1 ORDER BY id", (call_id,)):
        vals = evidence.setdefault(row["type"], [])
        if row["value"] not in vals:
            vals.append(row["value"])
    started = call["started_at"] or time.time()
    ended = call["ended_at"] or time.time()
    caller_turns = [t for t in turns if t["channel"] == "caller"]
    squash = lambda x: " ".join(re.findall(r"[a-z0-9@.]+", x.lower()))  # noqa: E731
    quotes, seen = [], set()
    for d in detections:
        for q in json.loads(d["evidence_quotes"] or "[]"):
            key = squash(q)
            if key in seen or not key:
                continue
            # The detector's quotes are LLM output: keep one only if the caller really said it, and time it from that turn.
            src = next((t for t in caller_turns if key in squash(t["text"])), None)
            if src is None:
                continue
            seen.add(key)
            quotes.append({"time": _clock(wall.get(src["id"], started)), "quote": q.strip(),
                           "stages": json.loads(d["stages"] or "[]")})
    quotes = [q for q in quotes if not any(o is not q and o["time"] == q["time"] and squash(q["quote"]) in squash(o["quote"])
                                           and len(o["quote"]) > len(q["quote"]) for o in quotes)]
    transcript = []
    for t in turns:
        who = {"caller": "Caller", "receiver": "You", "persona": "Kavach decoy persona (fake details)"}.get(t["channel"], t["channel"])
        transcript.append({"time": _clock(wall.get(t["id"], started)), "who": who, "text": t["text"]})
    r = Report(
        call_id=call_id, incident_time=_ist(started) or "unknown", duration=f"{max(0, round(ended - started))} seconds",
        caller_number=call["caller_number"] or "unknown (not captured)", stages=stages,
        peak_risk=call["max_risk"] or 0, warned_at=_ist(call["warned_at"]), takeover_at=_ist(call["takeover_at"]),
        evidence=evidence, key_quotes=quotes[:12], transcript=transcript,
        money_shared=None if call["money_shared"] is None else bool(call["money_shared"]),
        otp_shared=None if call["otp_shared"] is None else bool(call["otp_shared"]), notes=notes)
    if not evidence.get("upi_id") and not evidence.get("bank_account"):
        r.missing.append("No UPI ID or bank account was stated by the caller on this call.")
    if call["caller_number"] is None:
        r.missing.append("The caller's number was not captured; add it from your phone's call log.")
    return r


def markdown(r: Report) -> str:
    L = [f"# Cyber-fraud complaint draft (for 1930 / cybercrime.gov.in)", "", f"> **{BANNER}**", "",
         "## Incident", "",
         f"- **Date and time:** {r.incident_time}", f"- **Call length:** {r.duration}",
         f"- **Caller's number:** {r.caller_number}",
         f"- **Scam stages detected:** {', '.join(STAGE_NAMES.get(s, s) for s in r.stages) or 'none recorded'} (peak risk {round(r.peak_risk)}/100)",
         f"- **Family-voice warning played:** {r.warned_at or 'no'}",
         f"- **Kavach took over the call:** {r.takeover_at or 'no'}",
         "", "## What the caller claimed and asked for", ""]
    for key, label in EVIDENCE_LABELS:
        vals = r.evidence.get(key)
        L.append(f"- **{label}:** {'; '.join(vals) if vals else 'none stated'}")
    L += ["", "## Did you lose anything? (you must confirm these)", "",
          f"- **Money sent:** {_yn(r.money_shared)}", f"- **OTP / PIN / card details shared:** {_yn(r.otp_shared)}"]
    if r.notes:
        L += ["", f"- **Your notes:** {r.notes}"]
    L += ["", "## Key quotes from the caller", ""]
    L += [f"- `{q['time']}` “{q['quote']}”" for q in r.key_quotes] or ["- none captured"]
    if r.missing:
        L += ["", "## Gaps to fill in before filing", ""] + [f"- {m}" for m in r.missing]
    L += ["", "## Call transcript", ""] + [f"- `{t['time']}` **{t['who']}:** {t['text']}" for t in r.transcript]
    L += ["", "## What to do next", ""] + [f"{i}. {s}" for i, s in enumerate(NEXT_STEPS, 1)]
    L += ["", "---", f"*{BANNER}* Generated {ist_now()}."]
    return "\n".join(L) + "\n"


def pdf(r: Report, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    ss = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=9.5, leading=13)
    small = ParagraphStyle("s", parent=body, fontSize=8, textColor=colors.HexColor("#555555"))
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=12, spaceBefore=10, spaceAfter=4)
    banner = ParagraphStyle("ban", parent=body, backColor=colors.HexColor("#fff3cd"), borderColor=colors.HexColor("#b26a00"),
                            borderWidth=1, borderPadding=6, textColor=colors.HexColor("#5c3a00"), fontName="Helvetica-Bold")
    P = lambda t, st=body: Paragraph(escape(t), st)  # noqa: E731
    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                            bottomMargin=16 * mm, title="Kavach complaint draft", author="Kavach")
    S = [P("Cyber-fraud complaint draft", ss["Title"]), P("for the National Cyber Crime Helpline 1930 and cybercrime.gov.in", small),
         Spacer(1, 6), P(BANNER, banner), Spacer(1, 8), P("Incident", h2)]

    def table(rows):
        t = Table([[P(a, ParagraphStyle("k", parent=body, fontName="Helvetica-Bold")), P(b)] for a, b in rows],
                  colWidths=[52 * mm, 118 * mm])
        t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.lightgrey)]))
        return t

    S.append(table([("Date and time", r.incident_time), ("Call length", r.duration), ("Caller's number", r.caller_number),
                    ("Scam stages detected", ", ".join(STAGE_NAMES.get(s, s) for s in r.stages) or "none recorded"),
                    ("Peak risk", f"{round(r.peak_risk)} / 100"), ("Warning played", r.warned_at or "no"),
                    ("Kavach took over", r.takeover_at or "no")]))
    S += [P("What the caller claimed and asked for", h2),
          table([(label, "; ".join(r.evidence.get(key, [])) or "none stated") for key, label in EVIDENCE_LABELS])]
    S += [P("Did you lose anything? (please confirm)", h2),
          table([("Money sent", _yn(r.money_shared)), ("OTP / PIN / card details shared", _yn(r.otp_shared))]
                + ([("Your notes", r.notes)] if r.notes else []))]
    S.append(P("Key quotes from the caller", h2))
    S += [P(f"{q['time']}   “{q['quote']}”") for q in r.key_quotes] or [P("none captured")]
    if r.missing:
        S.append(P("Gaps to fill in before filing", h2))
        S += [P("• " + m) for m in r.missing]
    S.append(P("What to do next", h2))
    S += [P(f"{i}. {s}") for i, s in enumerate(NEXT_STEPS, 1)]
    S += [P("Call transcript", h2)] + [P(f"{t['time']}  {t['who']}: {t['text']}", small) for t in r.transcript]
    S += [Spacer(1, 8), P(f"{BANNER} Generated {ist_now()}.", small)]

    def footer(canvas, d):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(colors.HexColor("#b26a00"))
        canvas.drawString(18 * mm, 9 * mm, "DRAFT — review before filing")
        canvas.drawRightString(A4[0] - 18 * mm, 9 * mm, f"Page {d.page}")
        canvas.restoreState()

    doc.build(S, onFirstPage=footer, onLaterPages=footer)
    return path


def generate(store, call_id: str, out_dir: str, notes: str = "") -> tuple[Report, Path, Path]:
    r = build(store, call_id, notes)
    base = Path(out_dir)
    base.mkdir(parents=True, exist_ok=True)
    md = base / f"{call_id}.md"
    md.write_text(markdown(r))
    pdf_path = pdf(r, base / f"{call_id}.pdf")
    store.update_call(call_id, report_md_path=str(md), report_pdf_path=str(pdf_path))
    return r, md, pdf_path
